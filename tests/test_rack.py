def make_exe(path: Path, script: Path) -> Path:
    if os.name == "nt":
        path = path.with_suffix(".cmd")
        path.write_text(f'@"{sys.executable}" "{script}" %*\n')
        return path
    path.write_text(f'#!/bin/sh\nexec "{sys.executable}" "{script}" "$@"\n')
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return path


class RackTestCase(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.bin = self.root / "_bin"
        self.bin.mkdir()
        make_exe(self.bin / "kaggle", FAKES / "fake_kaggle.py")
        fake_py = make_exe(self.bin / "fake-unsloth-python", FAKES / "fake_train_python.py")
        (self.root / "rack.toml").write_text(textwrap.dedent(f"""
            [kaggle]
            username = "fakeuser"
            poll_seconds = 0
            dataset_settle_seconds = 0
            timeout_minutes = 1
            [local_train]
            python = '{fake_py}'  # literal string: Windows paths have backslashes
        """))
        self.fake = FakeOllama().__enter__()
        self.env_backup = os.environ.copy()
        os.environ.update({"RACK_HOME": str(self.root), "RACK_OLLAMA_URL": self.fake.url,
                           "FAKE_KAGGLE_STATE": str(self.root / "_kaggle.json"), "NO_COLOR": "1",
                           "PATH": f"{self.bin}{os.pathsep}{os.environ.get('PATH', '')}"})
        for k in ("FAKE_KAGGLE_FAIL", "FAKE_KAGGLE_CRASH", "FAKE_KAGGLE_MISSING_MODULE", "KAGGLE_USERNAME"):
            os.environ.pop(k, None)

    def tearDown(self):
        self.fake.__exit__()
        os.environ.clear()
        os.environ.update(self.env_backup)
        self.tmp.cleanup()

    def rack(self, *args, stdin: str | None = None) -> tuple[int, str]:
        out, err = io.StringIO(), io.StringIO()
        old_stdin = sys.stdin
        if stdin is not None:
            sys.stdin = io.StringIO(stdin)
        try:
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                code = cli.main(list(args))
        finally:
            sys.stdin = old_stdin
        return code, out.getvalue() + err.getvalue()

    def ok(self, *args, **kw) -> str:
        code, text = self.rack(*args, **kw)
        self.assertEqual(code, 0, f"rack {' '.join(args)} failed:\n{text}")
        return text

    def reg(self, name: str) -> Registry:
        return Registry(self.root / "models" / name, name)


class TestUnits(unittest.TestCase):
    def test_modelfile_parse(self):
        text = textwrap.dedent('''
            # generated by Unsloth
            FROM ./model.Q4_K_M.gguf
            TEMPLATE """{{- if .System }}<|im_start|>system
            {{ .System }}<|im_end|>
            {{ end }}"""
            PARAMETER stop "<|im_end|>"
            PARAMETER stop "<|im_start|>"
            PARAMETER temperature 0.7
            PARAMETER num_ctx 4096
            SYSTEM You are helpful.
            MESSAGE user "Hi"
            MESSAGE assistant """Hello
            there"""
            LICENSE """Apache 2.0"""
        ''')
        m = modelfile.parse(text)
        self.assertEqual(m["from"], "./model.Q4_K_M.gguf")
        self.assertIn("<|im_start|>system\n{{ .System }}", m["template"])
        self.assertEqual(m["parameters"]["stop"], ["<|im_end|>", "<|im_start|>"])
        self.assertEqual(m["parameters"]["temperature"], 0.7)
        self.assertEqual(m["parameters"]["num_ctx"], 4096)
        self.assertEqual(m["system"], "You are helpful.")
        self.assertEqual(m["messages"], [{"role": "user", "content": "Hi"},
                                         {"role": "assistant", "content": "Hello\nthere"}])
        self.assertEqual(m["license"], ["Apache 2.0"])
        self.assertEqual(modelfile.infer_stops("<|im_start|>user"), ["<|im_end|>", "<|im_start|>"])
        self.assertIn("<|eot_id|>", modelfile.infer_stops("<|start_header_id|>user<|end_header_id|>"))
        self.assertEqual(modelfile.infer_stops("{{ .Prompt }}"), [])
        self.assertEqual(modelfile.infer_stops(None), [])

