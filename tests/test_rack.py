    def test_data_formats(self):
        n = data.normalize
        self.assertEqual(n({"prompt": "a", "response": "b"})[1], {"role": "assistant", "content": "b"})
        self.assertEqual(n({"instruction": "do", "input": "x", "output": "y"})[0]["content"], "do\n\nx")
        self.assertEqual(n({"conversations": [{"from": "human", "value": "q"}, {"from": "gpt", "value": "a"}]})[1]["role"],
                         "assistant")
        for bad, why in [({"messages": [{"role": "user", "content": "q"}]}, "at least one"),
                         ({"messages": [{"role": "user", "content": "q"}, {"role": "assistant", "content": " "}]}, "empty"),
                         ({"messages": [{"role": "assistant", "content": "a"}, {"role": "user", "content": "q"}]}, "last"),
                         ({"foo": 1}, "unrecognized")]:
            with self.assertRaises(ValueError) as cm:
                n(bad)
            self.assertIn(why, str(cm.exception))

